import {readFile, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {parseArgs} from 'node:util';

const root = fileURLToPath(new URL('../', import.meta.url));

/** Produces the deployment manifest from the local tested Compose, with immutable Git source. */
export function oficinaCompose(source, commit) {
  if (!/^[a-f0-9]{40}$/u.test(commit || '')) throw new Error('Informe o SHA completo de um commit publicado e verificado.');
  for (const marker of ['    context: .\n', '  image: ab-jk-uash:local\n']) {
    if (source.split(marker).length !== 2) throw new Error('O Compose base mudou. Revise o gerador antes de implantar.');
  }
  if (/^  verification:/mu.test(source)) throw new Error('O Compose já define verificação. Revise o gerador.');
  const image = `ab-jk-uash:${commit.slice(0, 12)}`;
  const header = `# Generated by scripts/jk-oficina-compose.mjs\n# Public Git source: ${commit}\n# Private database and credentials remain in ../dados.\n`;
  const pinned = source.replace('    context: .\n', `    context: https://github.com/oalexandrebelo/AB-JK-UASH.git#${commit}\n`).replace('  image: ab-jk-uash:local\n', `  image: ${image}\n`);
  return `${header}${pinned.trimEnd()}\n
  verification:
    image: ${image}
    user: "1001:1001"
    init: true
    restart: "no"
    read_only: true
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - ALL
    pids_limit: 32
    mem_limit: 96m
    cpus: "0.25"
    command: ["node", "scripts/jk-runtime-probe.mjs", "--hostname", "app"]
    environment:
      PUBLIC_ORIGIN: https://ab-pcsrv.tail6bac78.ts.net:\${AB_PORTA:-9220}
    depends_on:
      app:
        condition: service_healthy
      maintenance:
        condition: service_healthy
    logging:
      driver: json-file
      options:
        max-size: 1m
        max-file: "2"
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const {values, positionals} = parseArgs({options: {commit: {type: 'string'}, out: {type: 'string'}}, allowPositionals: true});
    if (positionals.length || !values.out) throw new Error('Use --commit SHA_COMPLETO --out CAMINHO_NOVO.');
    const output = resolve(values.out);
    if (output === resolve(root, 'compose.yaml')) throw new Error('Não sobrescreva o Compose base; gere o manifesto em outro arquivo.');
    const text = oficinaCompose(await readFile(resolve(root, 'compose.yaml'), 'utf8'), values.commit);
    await writeFile(output, text, {flag: 'wx', mode: 0o640});
    console.log(JSON.stringify({ok: true, file: output, sourceCommit: values.commit, privateDataIncluded: false}));
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
