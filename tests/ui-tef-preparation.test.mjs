import test from 'node:test';
import assert from 'node:assert/strict';
import {fixture,until,fill,click,submit,button,uiQaAvailable,uiQaSkipReason} from './ui-helpers.mjs';

test('preparação TEF salva múltiplos fornecedores sem habilitar cobrança, com versão e acesso administrativo', {timeout:90000,skip:!uiQaAvailable&&uiQaSkipReason}, async t=>{
  const f=await fixture(t);
  await until(()=>f.text().includes('Prepare a operação JK'),'primeiro acesso');
  await fill(f,'Seu nome','Admin TEF QA');await fill(f,'E-mail','tef-admin@example.test');await fill(f,'Senha','Senha-sintetica-12345');
  await submit(f,'Criar acesso de administrador');await until(()=>f.text().includes('Visão geral'),'admin autenticado');
  assert.equal((await f.api('/users',{method:'POST',body:{name:'Gestor TEF QA',email:'tef-manager@example.test',password:'Senha-manager-12345',role:'manager'}})).status,201);
  const count=async table=>(await f.app.store.prepare(`SELECT COUNT(*) AS count FROM ${table}`).get()).count;
  const payments=await count('payments');
  const catalog=(await f.api('/jk/tef/catalog')).data;
  assert.ok(catalog.providers.length>=2);
  assert.ok(catalog.providers.every(provider=>provider.connectorImplemented===false));
  const selected=catalog.providers.slice(0,2);
  const route=async()=>{await f.route('integrations');await until(()=>f.text().includes('Prepare suas próximas integrações'),'central de preparação');};
  await route();
  const guideCards=()=>[...f.document.querySelectorAll('.integration-guide')];
  assert.equal(guideCards().length,6);
  await fill(f,'Buscar roteiro de integração','MIGRACAO');
  assert.equal(guideCards().length,1);assert.ok(guideCards()[0].textContent.includes('02/11 é a data pretendida.'));
  await fill(f,'Buscar roteiro de integração','inexistente-no-catalogo');
  assert.ok(f.text().includes('Nenhum roteiro com este termo'));
  await fill(f,'Buscar roteiro de integração','');
  let copiedText='';
  Object.defineProperty(f.window.navigator,'clipboard',{configurable:true,value:{writeText:async value=>{copiedText=value;}}});
  guideCards()[0].open=true;
  await click(f,'Copiar roteiro de Pix com Asaas');
  assert.ok(copiedText.includes('https://docs.asaas.com/reference/comece-por-aqui'));
  assert.ok(copiedText.includes('conexão e homologação exigem evidências próprias'));
  assert.ok(f.text().includes('Roteiro de Pix com Asaas copiado.'));
  assert.ok(f.text().includes('Guia de implantação por fornecedor'));
  await click(f,'Conferir preparação local');
  await until(()=>f.text().includes('Nenhum fornecedor salvo para preparar.'),'diagnóstico sem seleção');
  for(const [index,provider] of selected.entries()){
    await until(()=>!button(f,`Preparar ${provider.label}`).disabled,'plano carregado');
    await click(f,`Preparar ${provider.label}`);
    await fill(f,'Modelo do equipamento',`Modelo sintético ${index+1}`);
    await fill(f,'Observações da instalação',`Caixa sintético ${index+1}`);
    await submit(f,'Salvar preparação');
    await until(()=>f.text().includes(`Preparação de ${provider.label} salva.`),'confirmação persistida');
  }
  let plan=(await f.api('/jk/tef/plan')).data;
  await click(f,'Conferir preparação local');
  await until(()=>f.text().includes('2 fornecedores salvos. Nenhum conector de cartão implementado.'),'diagnóstico das seleções');
  assert.ok(f.text().includes('Equipamento informado; conector pendente.'));
  assert.ok(f.document.querySelector('.tef-step-guide summary'),'Roteiro usa expansão nativa acessível.');
  const providerGuide=f.document.querySelector('.tef-step-guide');providerGuide.open=true;
  await click(f,`Copiar roteiro de ${selected[0].label}`);
  assert.ok(copiedText.includes('Conector JK: não implementado.'));
  assert.equal(copiedText.includes('Modelo sintético'),false);assert.equal(copiedText.includes('Caixa sintético'),false);
  assert.equal(plan.providers.length,2);assert.equal(plan.canSubmit,false);assert.equal(plan.connectionVerified,false);assert.equal(plan.homologated,false);
  assert.equal(plan.providers[1].terminalModel,'Modelo sintético 2');
  await f.restart();assert.deepEqual((await f.api('/jk/tef/plan')).data,plan);
  await until(()=>!button(f,`Revisar ${selected[0].label}`).disabled,'plano atualizado');
  await click(f,`Revisar ${selected[0].label}`);
  const changed=plan.providers.map((provider,index)=>index?provider:{...provider,notes:'Outra sessão sintética'});
  assert.equal((await f.api('/jk/tef/plan',{method:'PATCH',body:{version:plan.version,providers:changed}})).status,200);
  await fill(f,'Observações da instalação','Rascunho concorrente');await submit(f,'Salvar preparação');
  await until(()=>f.requests.filter(row=>row.path==='/api/jk/tef/plan'&&row.method==='PATCH').at(-1)?.status===409,'conflito de versão');
  assert.ok(f.document.querySelector('[role="dialog"]'),'Conflito preserva diálogo e rascunho.');
  assert.equal((await f.api('/jk/tef/plan')).data.providers[0].notes,'Outra sessão sintética');
  await click(f,'Voltar');await click(f,'Atualizar preparação');
  await until(()=>!button(f,`Revisar ${selected[1].label}`).disabled,'recarregar versão');
  const transition=(await f.api('/jk/transition')).data;
  assert.equal((await f.api('/jk/transition',{method:'PATCH',body:{version:transition.version,mode:'parallel_readonly'}})).status,200);
  await click(f,`Revisar ${selected[1].label}`);await fill(f,'Observações da instalação','Preparação durante consulta');await submit(f,'Salvar preparação');
  await until(()=>f.text().includes(`Preparação de ${selected[1].label} salva.`),'preparação em consulta paralela');
  plan=(await f.api('/jk/tef/plan')).data;assert.equal(plan.providers[1].notes,'Preparação durante consulta');assert.equal(plan.canSubmit,false);
  assert.equal(await count('payments'),payments);
  assert.ok(f.text().includes('Nenhuma máquina foi ativada.'));
  await click(f,'Sair');await until(()=>f.text().includes('Vamos começar o dia?'),'logout');
  await fill(f,'E-mail','tef-manager@example.test');await fill(f,'Senha','Senha-manager-12345');await submit(f,'Entrar na operação');
  await until(()=>f.text().includes('Gestor TEF QA'),'gestor autenticado');await route();
  await until(()=>f.text().includes('Um administrador pode salvar a preparação.'),'consulta gestor');
  assert.equal([...f.document.querySelectorAll('button')].some(node=>node.textContent.startsWith('Preparar ')||node.textContent.startsWith('Revisar ')),false);
  assert.equal((await f.api('/jk/tef/plan',{method:'PATCH',body:{version:plan.version,providers:[]}})).status,403);
  assert.deepEqual((await f.api('/jk/tef/plan')).data,plan);assert.equal(await count('payments'),payments);
  assert.equal(f.runtimeErrors.length,0,f.runtimeErrors.map(error=>error.message).join('\n'));
});
